#!/usr/bin/env python3
"""
run_figure_generation.py

Generate the final LUNAR GitHub figure set using standardized filenames.

Expected final outputs:
  Figure_01_Zscore_Heatmaps.png
  Figure_02_FullReference_Mahalanobis_Trajectories.png
  Figure_03_Bootstrap_Mahalanobis_KDE.png
  Figure_04_Bootstrap_Mahalanobis_Violin.png
"""

from pathlib import Path
import subprocess
import sys

PYTHON = sys.executable
SCRIPT_DIR = Path(__file__).resolve().parent

# Edit these if your outputs live elsewhere.
FINAL18_WORKBOOK = Path("outputs/workbooks/LUNAR_Final18_Statistical_Comparison_Workbook.xlsx")
MAHALANOBIS_BOOTSTRAP_WORKBOOK_DIR = Path("outputs/workbooks")  # folder containing mahalanobis_distance_summary.xlsx


def run(cmd, cwd=None):
    print("\nRUN:", " ".join(map(str, cmd)))
    subprocess.run(cmd, cwd=cwd, check=True)


def main():
    # Figure 01
    run([
        PYTHON,
        str(SCRIPT_DIR / "generate_zscore_heatmaps.py"),
        "--input", str(FINAL18_WORKBOOK),
        "--output", "Figure_01_Zscore_Heatmaps.png",
    ])

    # Figure 02 is generated by lunar_full_reference_mahalanobis.py during the full-reference analysis.
    # It now saves as Figure_02_FullReference_Mahalanobis_Trajectories.png.

    # Figure 03 is generated from mahalanobis_distance_summary.xlsx.
    # Run this from the directory containing that workbook.
    if (MAHALANOBIS_BOOTSTRAP_WORKBOOK_DIR / "mahalanobis_distance_summary.xlsx").exists():
        run([PYTHON, str(SCRIPT_DIR / "generate_realdata_kde_no_phase_titles.py")], cwd=MAHALANOBIS_BOOTSTRAP_WORKBOOK_DIR)
    else:
        print("Skipping Figure 03: mahalanobis_distance_summary.xlsx not found.")

    print("\nFigure generation helper complete.")


if __name__ == "__main__":
    main()
